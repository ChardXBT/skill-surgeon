"""Terminal + markdown reporting."""

from __future__ import annotations

import sys
from pathlib import Path

from .model import Finding, Report, Skill

_C = {"error": "\033[91m", "warn": "\033[93m", "info": "\033[96m",
      "ok": "\033[92m", "dim": "\033[2m", "bold": "\033[1m", "r": "\033[0m"}
_NO_COLOR = not sys.stdout.isatty()


def c(text: str, color: str) -> str:
    return text if _NO_COLOR else f"{_C.get(color, '')}{text}{_C['r']}"


def grade(score: int) -> str:
    return ("A" if score >= 90 else "B" if score >= 75 else
            "C" if score >= 60 else "D" if score >= 40 else "F")


def render_terminal(report: Report, roots: list[Path]) -> str:
    out: list[str] = []
    counts = report.counts()
    score = report.score()
    out.append("")
    out.append(c("SKILL SURGEON — health report", "bold"))
    for r in roots:
        out.append(c(f"  root: {r}", "dim"))
    sem = "on (local model)" if report.semantic_ok else f"off — {report.semantic_note}"
    out.append(c(f"  scanned {len(report.skills)} skills · semantic pass: {sem}", "dim"))
    out.append("")
    out.append(f"  score {c(str(score) + '/100 ' + grade(score), 'bold')}   "
               f"{c(str(counts['error']) + ' errors', 'error')}   "
               f"{c(str(counts['warn']) + ' warnings', 'warn')}   "
               f"{c(str(counts['info']) + ' suggestions', 'info')}")
    out.append("")

    sev_order = {"error": 0, "warn": 1, "info": 2}
    for f in sorted(report.findings, key=lambda x: (x.file.as_posix(), sev_order[x.severity], x.line)):
        loc = f"{f.file}"
        line = f":{f.line}" if f.line else ""
        tag = f.severity.upper().ljust(5)
        fixable = " [fixable]" if f.fixable else ""
        out.append(f"  {c(tag, f.severity)} {c(f.rule, 'dim')} {f.skill.ljust(28)[:28]} "
                   f"{f.message}{fixable}  {c(loc + line, 'dim')}")

    if not report.findings:
        out.append(c("  no findings — library is clean", "ok"))
    out.append("")
    return "\n".join(out)


def _md_escape(s: str) -> str:
    return s.replace("|", "\\|")


def render_markdown(report: Report, roots: list[Path]) -> str:
    counts = report.counts()
    lines = [
        "# Skill Surgeon — health report", "",
        f"**Score: {report.score()}/100 ({grade(report.score())})** — "
        f"{counts['error']} errors · {counts['warn']} warnings · {counts['info']} suggestions",
        "",
        f"Scanned **{len(report.skills)}** skills across {len(roots)} root(s). "
        f"Semantic pass (open-weight local model): "
        f"{'enabled' if report.semantic_ok else 'disabled — ' + report.semantic_note}.",
        "",
        "| Severity | Rule | Skill | Finding | Location |",
        "|---|---|---|---|---|",
    ]
    for f in sorted(report.findings, key=lambda x: (x.severity, x.skill)):
        loc = f"{f.file.name}:{f.line}" if f.line else f.file.name
        lines.append(f"| {f.severity} | {f.rule} | {_md_escape(f.skill)} | "
                     f"{_md_escape(f.message)} | `{loc}` |")
    if report.collisions:
        lines += ["", "## Trigger collisions (local model)", ""]
        for col in report.collisions:
            lines.append(f"- **{col.get('a')}** ↔ **{col.get('b')}** "
                         f"({col.get('confidence','?')}): {col.get('reason','')}")
    lines += ["", f"_generated by skill-surgeon_", ""]
    return "\n".join(lines)


def render_plan_md(fixes) -> str:
    lines = ["# Surgery plan", ""]
    for fx in fixes:
        auto = "" if fx.auto else " _(manual review)_"
        lines.append(f"## {fx.id} — {fx.skill} ({fx.rule}){auto}")
        lines.append(f"**{fx.kind}** — {fx.rationale}")
        if fx.kind == "replace_text":
            lines += ["", "```diff"]
            for l in fx.find.split("\n"):
                lines.append("- " + l)
            for l in fx.replace.split("\n"):
                lines.append("+ " + l)
            lines += ["```", ""]
    return "\n".join(lines)


def apply_fix(fix) -> tuple[bool, str]:
    """Apply a replace_text fix. Returns (ok, message)."""
    if fix.kind != "replace_text":
        return False, "not auto-applicable"
    p = Path(fix.file)
    try:
        raw = p.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return False, f"read failed: {e}"
    if not fix.find:
        return False, "empty find string"
    if fix.find not in raw:
        if fix.replace and fix.replace in raw:
            return True, "already applied"
        return False, "find string not present (file changed since scan?)"
    new = raw.replace(fix.find, fix.replace, 1)
    try:
        p.write_text(new, encoding="utf-8")
    except OSError as e:
        return False, f"write failed: {e}"
    return True, "applied"
